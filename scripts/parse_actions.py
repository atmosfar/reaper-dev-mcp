#!/usr/bin/env python3
"""
Parse the REAPER actions list HTML export into data/actions-api.json.

The HTML is generated by REAPER itself:
    Actions list window -> "Save list..." (or "Save as...") -> HTML

Expected structure:

    <p><font size=1>Generated by REAPER v7.80/macOS-arm64</font></p>
    <H2>Section: Main, Main (alt recording), Main (alt-1), ...</H2>
    <TABLE WIDTH="100%" id='list'>
      <TR><TD>Envelope: Insert new point ...</TD><TD style='display:none;'>40064</TD></TR>
    </TABLE>

Parsing notes / gotchas (all verified against a real export):

  1. Command IDs are only unique WITHIN a section. 7663 unique IDs across
     9413 rows; 1089 IDs resolve to different actions per section
     (41075 = "[developer] Debug console" in Main but
     "Set length for next inserted note: 1/4T" in MIDI Editor).
     => the record key is the pair (section, id).

  2. REAPER does NOT escape '<', '>' or '&' inside action names, and the file
     contains zero HTML entities. So we must not html.unescape(), and the row
     regex must not use [^<]* -- that silently drops the 10 rows whose names
     contain "<0/mid". Use a non-greedy group anchored on the closing tag.

  3. A <H2>Section: ...</H2> header lists every context that section covers.
     The Main table covers 18 contexts (Main, Main (alt recording),
     Main (alt-1)..Main (alt-16)).

  4. Category is implicit: the text before the first ": " is REAPER's own
     grouping prefix ("Envelope", "Track", "SWS/BR", ...). 531 rows have none.

  5. Source is derived from that prefix, NOT from the ID range. Extension
     actions overwhelmingly land in 50000+, but stock REAPER also registers
     actions there ("Video: Fullscreen", "Automation: Save latch preset N"),
     so ID band is not a reliable signal.

Usage:
    python3 scripts/parse_actions.py <ReaperActions.html> [output.json]
"""

import json
import re
import sys
from collections import Counter
from datetime import datetime
from pathlib import Path

# Row regex: non-greedy, anchored on the closing tag so that raw '<' and '>'
# inside action names are preserved instead of breaking the match.
ROW_RE = re.compile(
    r"<TR><TD>(.*?)</TD><TD style='display:none;'>\s*(\d+)\s*</TD></TR>", re.S
)
SECTION_RE = re.compile(r"<H2>\s*Section:\s*(.*?)\s*</H2>", re.S)
VERSION_RE = re.compile(r"Generated by REAPER\s+([^<\r\n]+)")

# Which sections each stock REAPER action section can be invoked from, plus
# the ReaScript entry point used to run actions of that section.
SECTION_ENTRY_POINTS = {
    "Main": {
        "lua": "reaper.Main_OnCommand(cmd, 0)",
        "note": "Main_OnCommandEx for non-native actions; "
                "NamedCommandLookup('_NAME') for extension actions",
    },
    "MIDI Editor": {
        "lua": "reaper.MIDIEditor_OnCommand(midieditor, cmd)",
        "note": "MIDIEditor_LastFocused_OnCommand targets the focused editor",
    },
    "MIDI Event List Editor": {
        "lua": None,
        "note": "no dedicated stock ReaScript entry point",
    },
    "MIDI Inline Editor": {
        "lua": None,
        "note": "no dedicated stock ReaScript entry point",
    },
    "Media Explorer": {
        "lua": None,
        "note": "no dedicated stock ReaScript entry point; "
                "see OpenMediaExplorer, MediaExplorerGetLastPlayedFileInfo",
    },
    "Crossfade Editor": {
        "lua": "reaper.CrossfadeEditor_OnCommand(cfeditor, cmd)",
        "note": "",
    },
}


def classify_source(name: str) -> tuple[str, str | None]:
    """Split an action name into (source, category).

    source is "reaper" for stock actions and "sws" for the SWS extension family.
    Anything not portable to another install is reported as "other" or "script"
    and dropped by the caller:

      - "script": per-install ReaScript actions, always rendered as
        "Script: <filename>.lua" (e.g. "Script: atmosfar_Multicam Editor.lua").
        These are the user's own/ReaPack-installed scripts: the set and the
        assigned IDs exist only on the machine that exported the list.
      - "other": third-party vendors outside SWS (Helgobox, ReaPack) whose
        numeric IDs are meaningless without that extension.

    Beware two look-alikes that ARE stock and must be kept: the "ReaScript:"
    category ("ReaScript: Run last ReaScript...", native IDs in the 4xxxx range)
    and stock categories holding a slash ("Markers/Regions", "I/O dialog",
    "File/Notation", "Region/Marker manager").
    """
    prefix = name.split(": ", 1)[0].strip() if ": " in name else ""
    category = prefix or None

    # Per-install ReaScript actions: category is exactly "Script" and the name
    # is always "Script: <file>.lua|.py|.js". Never "ReaScript:".
    if prefix.lower() == "script" or re.match(r"^Script:\s", name):
        return "script", category

    if prefix == "SWS" or prefix.startswith("SWS/") or "/SWS" in prefix:
        return "sws", category

    if re.search(r"helgobox", prefix, re.I) or prefix == "ReaPack" or prefix.startswith("ReaPack/"):
        return "other", category

    return "reaper", category


def parse_actions_html(html_text: str) -> dict:
    """Parse the whole export into the data structure written to JSON."""
    version_match = VERSION_RE.search(html_text)
    generated_by = version_match.group(1).strip() if version_match else None

    headers = [(m.start(), m.group(1)) for m in SECTION_RE.finditer(html_text)]
    if not headers:
        raise ValueError("no <H2>Section: ...</H2> headers found; is this a REAPER actions export?")

    actions: list[dict] = []
    sections: list[dict] = []
    dropped = Counter()

    for index, (start, header) in enumerate(headers):
        end = headers[index + 1][0] if index + 1 < len(headers) else len(html_text)
        body = html_text[start:end]

        # e.g. "Main, Main (alt recording), Main (alt-1)" -> list of contexts
        contexts = [c.strip() for c in re.split(r",\s*(?![^(]*\))", header) if c.strip()]
        section_name = contexts[0]

        kept = 0
        for raw_name, raw_id in ROW_RE.findall(body):
            name = raw_name.strip()
            command_id = raw_id.strip()

            source, category = classify_source(name)
            if source in ("other", "script"):
                dropped[f"{category or '(no prefix)'} [{source}]"] += 1
                continue

            # contexts are intentionally NOT stored per action: they are a pure
            # function of the section (Main alone would repeat the same 18
            # strings 6946 times, adding ~3MB). They live in sections[] and the
            # DataLoader re-attaches them to results.
            actions.append(
                {
                    "id": command_id,
                    "section": section_name,
                    "name": name,
                    "category": category,
                    "source": source,
                }
            )
            kept += 1

        entry = SECTION_ENTRY_POINTS.get(section_name, {})
        sections.append(
            {
                "name": section_name,
                "contexts": contexts,
                "action_count": kept,
                "invoke": entry.get("lua"),
                "notes": entry.get("note") or None,
            }
        )

    # --- integrity checks -------------------------------------------------
    raw_rows = len(re.findall(r"<TR><TD>", html_text))
    kept_and_dropped = len(actions) + sum(dropped.values())
    if raw_rows != kept_and_dropped:
        raise ValueError(
            f"lossless parse failed: {raw_rows} raw rows vs {kept_and_dropped} accounted for"
        )

    keys = [(a["section"], a["id"]) for a in actions]
    duplicates = [k for k, n in Counter(keys).items() if n > 1]
    if duplicates:
        raise ValueError(f"composite key (section,id) not unique, e.g. {duplicates[:3]}")

    for a in actions:
        if "<TD" in a["name"] or "</TD" in a["name"]:
            raise ValueError(f"table markup leaked into action name: {a['name'][:80]}")

    if dropped:
        print(
            "Dropped non-portable actions (per-install scripts, non-SWS vendors): "
            + ", ".join(f"{k} ({v})" for k, v in dropped.most_common()),
            file=sys.stderr,
        )

    return {
        "actions": actions,
        "sections": sections,
        "generated_by": generated_by,
        "scraped_at": datetime.now().isoformat(),
        "total_actions": len(actions),
        "counts_by_section": {s["name"]: s["action_count"] for s in sections},
        "counts_by_source": dict(Counter(a["source"] for a in actions)),
    }


def main() -> None:
    if len(sys.argv) < 2:
        print(__doc__, file=sys.stderr)
        sys.exit(1)

    input_path = Path(sys.argv[1])
    if not input_path.exists():
        print(f"Error: input file not found: {input_path}", file=sys.stderr)
        sys.exit(1)

    output_path = (
        Path(sys.argv[2])
        if len(sys.argv) > 2
        else Path(__file__).parent.parent / "data" / "actions-api.json"
    )

    print(f"Parsing REAPER actions list from {input_path}...", file=sys.stderr)
    data = parse_actions_html(input_path.read_text(encoding="utf-8"))

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)

    print(f"\nSaved actions data to {output_path}", file=sys.stderr)
    print(
        f"Total: {data['total_actions']} actions in {len(data['sections'])} sections"
        f"  (REAPER {data['generated_by']})",
        file=sys.stderr,
    )
    for name, count in data["counts_by_section"].items():
        print(f"  {name:26s} {count:5d}", file=sys.stderr)
    print(f"  by source: {data['counts_by_source']}", file=sys.stderr)


if __name__ == "__main__":
    main()
